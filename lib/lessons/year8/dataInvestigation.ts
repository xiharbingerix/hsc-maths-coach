// ── Helper builders ──────────────────────────────────────────────────────────

function answer(
  id: string,
  prompt: string,
  latex: string,
  value: string,
  explanation: string,
  hint: string,
  acceptedAnswers: string[] = [],
  difficulty?: number
): PracticeQuestion {
  const q: PracticeQuestion = {
    id,
    prompt,
    latex,
    answer: value,
    acceptedAnswers: Array.from(new Set([value, ...acceptedAnswers])),
    hint,
    explanation,
  };
  if (difficulty !== undefined) q.difficulty = difficulty;
  return q;
}

function choice(
  id: string,
  prompt: string,
  value: "A" | "B" | "C" | "D",
  choices: [string, string, string, string],
  explanation: string,
  hint: string,
  difficulty?: number,
  latex = "\\text{Select A, B, C or D.}"
): PracticeQuestion {
  const q: PracticeQuestion = {
    id,
    prompt,
    latex,
    choices: ["A", "B", "C", "D"].map((label, i) => ({ label, text: choices[i] })),
    answer: value,
    acceptedAnswers: [],
    hint,
    explanation,
  };
  if (difficulty !== undefined) q.difficulty = difficulty;
  return q;
}

